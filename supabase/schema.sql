create table if not exists public.duels (
  id bigint generated by default as identity primary key,
  played_on date not null,
  duration_minutes integer not null check (duration_minutes between 1 and 1440),
  claire_character text not null,
  maxence_character text not null,
  winner text not null check (winner in ('player1', 'player2', 'draw')),
  claire_comment text not null default '' check (char_length(claire_comment) <= 1000),
  maxence_comment text not null default '' check (char_length(maxence_comment) <= 1000),
  created_at timestamptz not null default now(),
  constraint different_characters check (claire_character <> maxence_character)
);

alter table public.duels enable row level security;

drop policy if exists "Authenticated members can read duels" on public.duels;
create policy "Authenticated members can read duels"
  on public.duels for select to authenticated
  using (auth.uid() is not null);

drop policy if exists "Authenticated members can add duels" on public.duels;
create policy "Authenticated members can add duels"
  on public.duels for insert to authenticated
  with check (auth.uid() is not null);

drop policy if exists "Authenticated members can edit duels" on public.duels;
create policy "Authenticated members can edit duels"
  on public.duels for update to authenticated
  using (auth.uid() is not null)
  with check (auth.uid() is not null);

drop policy if exists "Authenticated members can delete duels" on public.duels;
create policy "Authenticated members can delete duels"
  on public.duels for delete to authenticated
  using (auth.uid() is not null);

grant select, insert, update, delete on public.duels to authenticated;
grant usage, select on sequence public.duels_id_seq to authenticated;
